"""Goose adapter.

Goose keeps full provider definitions as JSON files in
~/.config/goose/custom_providers/ and references them from config.yaml.
This adapter writes one custom provider per managed modelhub provider,
updates config.yaml to enable all of them, and writes a launch environment
with all provider keys so `modelhub run goose` (or sourcing the env file)
works immediately.
"""
from __future__ import annotations

import io
import json
from pathlib import Path

from ruamel.yaml import YAML

from ..catalog import PROVIDERS
from ..safety import dumps_json
from .base import FileWrite, Plan, default_model, provider_slugs

CONFIG = Path.home() / ".config" / "goose" / "config.yaml"
CUSTOM_DIR = Path.home() / ".config" / "goose" / "custom_providers"
ENVFILE = Path.home() / ".config" / "modelhub" / "goose.env"


def _custom_name(slug: str) -> str:
    return f"custom_{slug}"


def _provider_json(name: str, meta: dict, models: list[dict]) -> dict:
    """Build a Goose custom provider JSON document."""
    return {
        "name": name,
        "engine": "openai",
        "display_name": meta["name"],
        "description": f"Custom {meta['name']} provider managed by modelhub",
        "api_key_env": meta["key"],
        "base_url": meta["base"],
        "models": [
            {
                "name": m["apiId"],
                "context_limit": int(m["ctx"]) if m.get("ctx") else None,
            }
            for m in models
        ],
        "headers": None,
        "session_id_header_override": None,
        "timeout_seconds": None,
        "supports_streaming": True,
        "requires_auth": True,
        "catalog_provider_id": None,
        "base_path": None,
        "env_vars": None,
        "auth": None,
        "dynamic_models": None,
        "skip_canonical_filtering": False,
        "model_doc_link": None,
        "setup_steps": [],
        "toolshim": False,
        "preserves_thinking": True,
        "emit_clear_thinking": False,
        "setup": None,
    }


def build(models: list[dict], keys: dict) -> Plan:
    pref = default_model(models)
    warnings: list[str] = []
    files: list[FileWrite] = []
    groups = provider_slugs(models)
    managed_providers: set[str] = set()

    if not pref:
        return Plan(app="goose", label="Goose", warnings=["no free model available"])

    CUSTOM_DIR.mkdir(parents=True, exist_ok=True)

    # Write one custom provider JSON per managed provider.
    for slug, items in groups.items():
        meta = PROVIDERS[slug]
        name = _custom_name(slug)
        managed_providers.add(name)
        path = CUSTOM_DIR / f"{name}.json"
        doc = _provider_json(name, meta, items)
        files.append(FileWrite(path, dumps_json(doc), "json", 0o600))

    # Clean up custom provider files for providers that are no longer managed.
    if CUSTOM_DIR.exists():
        for path in CUSTOM_DIR.glob("custom_*.json"):
            if path.stem in managed_providers:
                continue
            # Only remove if the file looks like one we wrote (has modelhub note).
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
                if "managed by modelhub" in (data.get("description") or ""):
                    files.append(FileWrite(path, "", "json", 0o600, delete=True))
            except (json.JSONDecodeError, OSError):
                pass

    # Update config.yaml: add/update every managed provider and set the default.
    yaml = YAML()
    yaml.preserve_quotes = True
    if CONFIG.exists():
        with open(CONFIG, encoding="utf-8") as f:
            doc = yaml.load(f)
    else:
        doc = {}

    providers = doc.setdefault("providers", {})

    # Remove stale managed-provider entries from config.yaml.
    for name in list(providers):
        if name.startswith("custom_") and name not in managed_providers:
            del providers[name]

    for slug, items in groups.items():
        name = _custom_name(slug)
        providers[name] = {
            "enabled": True,
            "model": items[0]["apiId"],
            "configured": True,
        }

    active = _custom_name(pref["provider"])
    old_active = doc.get("active_provider")
    doc["active_provider"] = active
    if old_active != active:
        warnings.append(f"active provider set to {active}")

    buf = io.StringIO()
    yaml.dump(doc, buf)
    files.append(FileWrite(CONFIG, buf.getvalue(), "yaml", 0o600))

    # Launch environment for `modelhub run goose` or manual sourcing.
    # Export every variable so child processes (goose) inherit them.
    env_lines = [
        "# generated by modelhub; source before launching goose",
        f"export GOOSE_PROVIDER={active}",
        f"export GOOSE_MODEL={pref['apiId']}",
    ]
    for slug in groups:
        key = keys.get(PROVIDERS[slug]["key"])
        if key:
            env_lines.append(f"export {PROVIDERS[slug]['key']}={key}")
        else:
            warnings.append(f"missing key for {slug} ({PROVIDERS[slug]['key']})")
    env_lines.append("")
    files.append(FileWrite(ENVFILE, "\n".join(env_lines), "env", 0o600))

    return Plan(
        app="goose",
        label="Goose",
        files=files,
        stats={
            "managed": sum(len(v) for v in groups.values()),
            "removed": 0,
            "providers": len(groups),
        },
        warnings=warnings,
        note="writes custom_providers/*.json + config.yaml + goose.env",
    )
